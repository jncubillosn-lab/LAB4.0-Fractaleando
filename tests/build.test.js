import {test} from 'node:test';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {readFileSync,existsSync,mkdirSync,writeFileSync} from 'node:fs';
test('Pages publica imports, workers y WASM con una misma identidad de caché',()=>{
 mkdirSync('_site',{recursive:true});
 writeFileSync('_site/obsolete-release.txt','Generated by a previous build');
 execFileSync(process.execPath,['scripts/build-site.mjs']);
 assert.equal(existsSync('_site/obsolete-release.txt'),false);
 for(const path of ['tests','docs','cloud','artifacts','node_modules','P1_Plano_R01_brazos_variables.html'])assert.equal(existsSync('_site/'+path),false,path);
 const html=readFileSync('_site/index.html','utf8'),build=html.match(/name="application-build" content="([a-f0-9]+)"/)[1];
 for(const file of ['index.html','js/app.js','js/views/DerivedViews.js','js/workers/derived-scene.worker.js','js/geometry/AvoidRouter.js','js/ui/NodeTypography.js',
  'js/io/GraphFile.js','js/ui/GraphFiles.js','js/ui/DiagramExport.js']){
  const text=readFileSync('_site/'+file,'utf8');
  const refs=[...text.matchAll(/(['"])(\.{1,2}\/[^'"\s]+\.(?:js|css|wasm|ttf|txt|gif|png|svg)(?:\?[^'"]*)?)\1/g)].map(m=>m[2]);
  assert.ok(refs.length,file);for(const ref of refs)assert.ok(ref.endsWith('?build='+build),ref);
 }
 assert.ok(existsSync('_site/js/vendor/libavoid.wasm'));assert.ok(existsSync('_site/js/vendor/LICENSE-libavoid.txt'));
 assert.ok(existsSync('_site/js/core/WorkerTask.js'));assert.ok(existsSync('_site/js/geometry/PlaneLayout.js'));
 for(const name of ['Rajdhani-SemiBold.ttf','Rajdhani-Bold.ttf','OFL-Rajdhani.txt'])assert.deepEqual(readFileSync('_site/css/fonts/'+name),readFileSync('css/fonts/'+name));
 for(const name of ['beaver-strip.png','favicon.svg'])assert.deepEqual(readFileSync('_site/css/images/'+name),readFileSync('css/images/'+name));
 const strip=readFileSync('_site/css/images/beaver-strip.png');
 assert.equal(strip.toString('ascii',1,4),'PNG');assert.equal(strip.readUInt32BE(16),768);assert.equal(strip.readUInt32BE(20),224);
 assert.equal(strip[24],1);assert.equal(strip[25],0);assert.ok(strip.length<=12000);
 assert.equal(existsSync('_site/css/images/loading.gif'),false);
});
